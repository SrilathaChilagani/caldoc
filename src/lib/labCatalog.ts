// ─── Lookup helpers ───────────────────────────────────────────────────────────

const _byCode = new Map(LAB_CATALOG.map((e) => [e.code.toLowerCase(), e]));
const _byName = new Map(LAB_CATALOG.map((e) => [e.name.toLowerCase(), e]));

export function findTestByCode(code: string): LabTestEntry | undefined {
  return _byCode.get(code.toLowerCase());
}

export function findTestByName(name: string): LabTestEntry | undefined {
  const n = name.toLowerCase().trim();
  if (_byName.has(n)) return _byName.get(n);
  return LAB_CATALOG.find(
    (e) => e.aliases.some((a) => a.toLowerCase() === n) || n.includes(e.code.toLowerCase()),
  );
}

export function searchCatalog(q: string, limit = 10): LabTestEntry[] {
  const term = q.toLowerCase().trim();
  if (!term || term.length < 2) return [];
  return LAB_CATALOG.filter(
    (e) =>
      e.name.toLowerCase().includes(term) ||
      e.code.toLowerCase().includes(term) ||
      e.aliases.some((a) => a.includes(term)),
  ).slice(0, limit);
}

export const LAB_TEST_OPTIONS: string[] = LAB_CATALOG.map((e) => e.name);
